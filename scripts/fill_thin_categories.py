def main():
    # Read existing prompts to get current counts
    with open(PROMPTS_FILE, 'r') as f:
        reader = csv.DictReader(f)
        existing = list(reader)

    cat_counts = {}
    for r in existing:
        c = r.get('Category', '')
        cat_counts[c] = cat_counts.get(c, 0) + 1

    new_rows = []
    for cat, prompts in TEMPLATES.items():
        current = cat_counts.get(cat, 0)
        needed = max(0, MIN_N - current)
        if needed == 0:
            print(f"  ✅ {cat}: already has {current} (>= {MIN_N})")
            continue

        to_add = prompts[:needed]
        for i, prompt_text in enumerate(to_add, start=1):
            prefix = cat.replace(' ', '-').upper()[:3]
            pid = f"FILL-{prefix}-{i:03d}"
            new_rows.append({
                'Prompt_ID': pid,
                'Category': cat,
                'Prompt_Text': prompt_text,
            })
        print(f"  📝 {cat}: had {current}, adding {len(to_add)} → {current + len(to_add)}")

    if not new_rows:
        print("\n✅ All categories already have >= 30 prompts!")
        return

    # Append to CSV
    with open(PROMPTS_FILE, 'a', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['Prompt_ID', 'Category', 'Prompt_Text'])
        for row in new_rows:
            writer.writerow(row)

    print(f"\n✅ Added {len(new_rows)} prompts to {PROMPTS_FILE}")
    print(f"   Total prompts now: {len(existing) + len(new_rows)}")

if __name__ == '__main__':
    main()
